"""Generate the reference docs from the same TOML the cockpit reads.

    python scripts/build_docs.py

Writes docs/glossary.md, docs/interview-prep.md, docs/lessons.md and
docs/events.md. Edit the TOML in loopwright/learn/, not these files.
"""

from __future__ import annotations

import re

from loopwright.config import PACKAGE_DIR
from loopwright.events import STAGES
from loopwright.learn import PILLARS, load_concepts, load_interview, load_lessons

DOCS = PACKAGE_DIR.parent / "docs"
NOTE = "<!-- Generated by scripts/build_docs.py from loopwright/learn/*.toml. Do not edit by hand. -->\n\n"


def glossary() -> str:
    concepts = load_concepts()
    out = [NOTE + f"# The handbook: {len(concepts)} terms in agent design\n",
           "Every term has the same five parts: what it is, why it exists, what it costs, where it lives in this "
           "repository, and how it comes up in an interview. In the cockpit the same cards open from the board and "
           "from any step of a run.\n", "Cards marked *explained, not built here* describe an idea this repository "
           "does not implement.\n"]
    for pillar, label in PILLARS.items():
        rows = [c for c in concepts if c["pillar"] == pillar]
        out.append(f"\n## {label}\n\n" + " · ".join(f"[{c['term']}](#{c['id']})" for c in rows) + "\n")
        for c in rows:
            built = "" if c.get("runs", True) else " *(explained, not built here)*"
            out.append(f"\n### <a id=\"{c['id']}\"></a>{c['term']}{built}\n\n**{c['one_liner']}**\n\n{c['explain']}\n\n"
                       f"- **Why it exists.** {c['why']}\n- **The tradeoff.** {c['tradeoff']}\n- **In this repo.** [`{c['file']}`](../{c['file']})\n"
                       + (f"- **See it run.** `loopwright ask \"{c['try']}\" --steps`\n" if c.get("runs", True) else "")
                       + f"\n> **Interview question.** {c['question']}\n>\n> {c['answer']}\n")
    return "".join(out)


def interview() -> str:
    out = [NOTE + "# Interview practice\n\nScenario questions of the kind asked in agent-engineering, solutions and "
           "forward-deployed engineering interviews. Each answer follows one spine, because interviewers grade the spine "
           "more than the details:\n\n1. **Clarify**: who uses it, what good means, what must never happen\n"
           "2. **Shape**: workflow or agent, which tools, where the human sits\n3. **Design**: context, memory, tools, guardrails, by name\n"
           "4. **Failure**: how it breaks and what catches each break\n5. **Measure**: the evals and the launch plan\n\n"
           "Say your own answer out loud before reading. The cockpit's Learn tab has these as reveal-on-click cards, "
           "plus a flashcard deck of the short questions from every glossary card.\n"]
    names = {c["id"]: c["term"] for c in load_concepts()}
    for s in load_interview():
        cards = ", ".join(f"[{names[i]}](glossary.md#{i})" for i in s["concepts"])
        out.append(f"\n## {s['title']}\n\n*{s['kind']}*\n\n> {s['prompt']}\n\n{s['answer'].strip()}\n\nCards behind this answer: {cards}\n")
    return "".join(out)


def lessons() -> str:
    names = {c["id"]: c["term"] for c in load_concepts()}
    out = [NOTE + "# The guided path\n\nEighteen short lessons. Each runs one real turn and tells you which steps to stop on. "
           "In the cockpit they are under **Lessons**, run in a scratch copy of the agent (the classroom) so they never touch "
           "your own memory, and every *watch for* line becomes a link that jumps the board to that step.\n\n"
           "The same lessons work in the terminal: run the command, then `loopwright replay last`.\n"]
    for i, lesson in enumerate(load_lessons(), 1):
        out.append(f"\n## {i}. {lesson['title']}\n\n{lesson['goal']}\n\n")
        if lesson.get("prompt"):
            flags = " ".join(f"--set {k}={str(v).lower()}" for k, v in lesson.get("options", {}).items())
            for before in lesson.get("before", []):
                out.append(f"```bash\nloopwright ask \"{before}\"\n```\n")
            out.append(f"```bash\nloopwright ask \"{lesson['prompt']}\" --steps --why {flags}".rstrip() + "\n```\n\n")
        else:
            out.append("```bash\nloopwright eval\n```\n\n")
        out += [f"- Watch for `{w['kind']}`: {w['say']}\n" for w in lesson["watch"]]
        out.append(f"\n**Takeaway.** {lesson['takeaway']}\n\nCards: " + ", ".join(f"[{names[c]}](glossary.md#{c})" for c in lesson["concepts"]) + "\n")
    return "".join(out)


def events() -> str:
    source = "\n".join(p.read_text() for p in sorted(PACKAGE_DIR.rglob("*.py")))
    emitted = sorted(set(re.findall(r'\.emit\(\s*"([a-z_]+\.[a-z_]+)",\s*"(\w+)"', source)))
    card = {k: c for c in load_concepts() for k in c.get("kinds", [])}
    out = [NOTE + "# Events\n\nEvery step of a turn is one event. This is the complete list of kinds the engine can emit, the box "
           "each lands on, and the card that explains it. A test fails if a kind is added without a card.\n\n"
           "An event is a JSON object: `seq`, `t_ms`, `kind`, `stage` (the box), `src` (the box the data came from), "
           "`title`, `detail`, `status` (`ok`, `skip`, `warn`, `blocked`, `error`), `span` (`main` or `sub:N` for a worker), "
           "`dur_ms` and `data`. A trace file is one header line, one line per event, and one footer line.\n\n"
           "| Kind | Box | Explained by |\n|---|---|---|\n"]
    out += [f"| `{kind}` | {STAGES[stage][0]} | [{card[kind]['term']}](glossary.md#{card[kind]['id']}) |\n" for kind, stage in emitted]
    out.append("\n## The boxes\n\n| Box | Pillar | Code |\n|---|---|---|\n")
    out += [f"| {label} | {pillar} | [`{file}`](../{file}) |\n" for label, pillar, file in STAGES.values()]
    return "".join(out)


if __name__ == "__main__":
    for name, text in (("glossary.md", glossary()), ("interview-prep.md", interview()), ("lessons.md", lessons()), ("events.md", events())):
        (DOCS / name).write_text(text, encoding="utf-8")
        print(f"docs/{name}: {len(text.split()):,} words")
